void main() {
  List<String> frutas = [
    'Maçã',
    'Melancia',
    'Uva',
    'Morango',
    'Maracujá'
  ];

  // Exibe toda a lista
  print(frutas);

  // Exibe o primeiro elemento
  print(frutas[0]);

  // Exibe o último elemento
  print(frutas[frutas.length - 1]);

  // Exibe a quantidade de elementos
  print(frutas.length);
}